text = input("Введите строку: ")

print(f"Длина: {len(text)}") # Выводит длину строки
print(f"Верхний регистр: {text.upper()}") # Вывод всехс символов с большой буквы
print(f"Нижний регистр: {text.lower()}") # Все символы в нижнем регистре
print(f"Первый символ: {text[0]}") # Выводит первый символ
print(f"Последний символ: {text[-1]}") # Выводит последний символ
print(f"Кол-во пробелов: {text.count(' ')}") # Выводит кол-во пробелов
